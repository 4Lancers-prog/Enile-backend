import { Router } from 'express';
import { authenticate } from './middleware/auth';
import { adminRouter } from './modules/admin/admin.routes';
import { authRouter } from './modules/auth/auth.routes';
import { companiesRouter } from './modules/companies/companies.routes';
import { dashboardRouter } from './modules/dashboard/dashboard.routes';
import { documentsRouter, ownerDocumentsRouter } from './modules/documents/documents.routes';
import { driversRouter } from './modules/drivers/drivers.routes';
import { filesRouter } from './modules/files/files.routes';
import { leadsRouter } from './modules/leads/leads.routes';
import { notificationsRouter } from './modules/notifications/notifications.routes';
import { quotationsRouter } from './modules/quotations/quotations.routes';
import { renewalsRouter } from './modules/renewals/renewals.routes';
import { exportsRouter, reportsRouter } from './modules/reports/reports.routes';
import { searchRouter } from './modules/search/search.routes';
import { statsRouter } from './modules/stats/stats.routes';
import { settingsRouter } from './modules/settings/settings.routes';
import { tripsRouter } from './modules/trips/trips.routes';
import { usersRouter } from './modules/users/users.routes';
import { vehiclesRouter } from './modules/vehicles/vehicles.routes';
import { inventoryRouter } from './modules/inventory/inventory.routes';
import { purchasesRouter } from './modules/purchases/purchases.routes';
import { expensesRouter } from './modules/expenses/expenses.routes';
import { payrollRouter } from './modules/payroll/payroll.routes';

/** Versioned REST API (manual 5.1, 12). Everything except /auth requires a session. */
export const apiV1 = Router();

apiV1.use('/auth', authRouter);
apiV1.use(authenticate);
apiV1.use('/dashboard', dashboardRouter);
apiV1.use('/search', searchRouter);
apiV1.use('/stats', statsRouter);
apiV1.use('/notifications', notificationsRouter);
apiV1.use('/users', usersRouter);
apiV1.use('/leads', leadsRouter);
apiV1.use('/companies', companiesRouter);
apiV1.use('/vehicles/:id/documents', ownerDocumentsRouter('vehicle'));
apiV1.use('/vehicles', vehiclesRouter);
apiV1.use('/drivers/:id/documents', ownerDocumentsRouter('driver'));
apiV1.use('/drivers', driversRouter);
apiV1.use('/documents', documentsRouter);
apiV1.use('/renewals', renewalsRouter);
apiV1.use('/quotations', quotationsRouter);
apiV1.use('/trips', tripsRouter);
apiV1.use('/trip-expenses', expensesRouter);
apiV1.use('/inventory', inventoryRouter);
apiV1.use('/purchase-orders', purchasesRouter);
apiV1.use('/payroll', payrollRouter);
apiV1.use('/reports', reportsRouter);
apiV1.use('/exports', exportsRouter);
apiV1.use('/settings', settingsRouter);
apiV1.use('/admin', adminRouter);
apiV1.use('/files', filesRouter);
